    const details = screen.getByRole('region', { name: '日程详情' })
    expect(within(details).getByRole('heading', { level: 3, name: calendarEvent.title })).toBeVisible()
    expect(details).toHaveTextContent('10月30日 周五 09:30 – 10:30')
    expect(details).toHaveTextContent(calendarEvent.location)
    expect(details).toHaveTextContent(calendarEvent.description)
