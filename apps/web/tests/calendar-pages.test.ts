    expect(screen.queryByRole('button', { name: allDay.title })).not.toBeInTheDocument()
    expect((await screen.findAllByRole('link', { name: `任务截止：${task.title}` })).length).toBeGreaterThan(0)
    const reads = requests.filter((r) => path(r) === '/api/v1/tasks').length
    await fireEvent.click(within(filters).getByLabelText('任务截止'))
    expect(screen.queryByRole('link', { name: `任务截止：${task.title}` })).not.toBeInTheDocument()
    expect(screen.getByText('此时间范围没有符合“显示内容”筛选的项目。')).toBeVisible()
    await fireEvent.click(screen.getByRole('button', { name: '刷新日历' }))
    expect(requests.filter((r) => path(r) === '/api/v1/tasks')).toHaveLength(reads)
    await fireEvent.click(within(filters).getByLabelText('日程'))
    expect(await screen.findByRole('button', { name: calendarEvent.title })).toBeVisible()
